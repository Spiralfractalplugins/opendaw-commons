#!/usr/bin/env python3
"""Embeds the interface files into a C++ header for the WebAssembly build.

The plugin serves the interface from its own memory - a page inside a wasm
sandbox cannot read anything else - so the files in web/ are turned into a
header here.

    python3 embed_web.py <web-dir> <output-header>
"""

import pathlib
import sys


def c_string(text: str, indent: str = "                ") -> str:
    """Escapes a text as C string literals, one chunk per source line."""
    lines = []
    for line in text.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        lines.append(f'{indent}"{escaped}"')
    if not lines:
        lines.append(f'{indent}""')
    lines[-1] += ","
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    web_dir = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2])

    files = sorted(p for p in web_dir.iterdir() if p.is_file())
    if not files:
        print(f"no interface files in {web_dir}", file=sys.stderr)
        return 1

    parts = [
        "#pragma once",
        "",
        "// Generated by wclap/tools/embed_web.py - do not edit.",
        "",
        "namespace spiral303",
        "{",
        "    namespace WebAssetData",
        "    {",
        "        struct Asset",
        "        {",
        "            const char* path;",
        "            const char* text;",
        "            int size;",
        "        };",
        "",
        "        inline constexpr Asset assets[] =",
        "        {",
    ]

    for path in files:
        text = path.read_text(encoding="utf-8")
        parts.append(f"            // {path.name}")
        parts.append("            {")
        parts.append(f'                "/{path.name}",')
        parts.append(c_string(text))
        parts.append(f"                {len(text.encode('utf-8'))}")
        parts.append("            },")

    parts.append("        };")
    parts.append("")
    parts.append(f"        inline constexpr int assetCount = {len(files)};")
    parts.append("    }")
    parts.append("}")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"embedded {len(files)} interface files into {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
