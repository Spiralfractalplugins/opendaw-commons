#!/usr/bin/env python3
"""Embeds the factory presets into a C++ header for the WebAssembly build.

The native build gets the presets from JUCE's binary data; the wasm build has
no such facility, so the same files are turned into a header here. The files
are the ones in presets/ - the format is untouched.

    python3 embed_presets.py <presets-dir> <output-header>
"""

import json
import pathlib
import sys


def c_string(text: str, indent: str = "                ") -> str:
    """Escapes a text as C string literals, one chunk per source line.

    The chunks are adjacent, so the compiler joins them into one string; the
    comma after the last one ends the initialiser.
    """
    lines = []
    for line in text.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        lines.append(f'{indent}"{escaped}"')
    if not lines:
        lines.append(f'{indent}""')
    lines[-1] += ","
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    presets_dir = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2])

    files = sorted(presets_dir.glob("*.json"))
    if not files:
        print(f"no presets found in {presets_dir}", file=sys.stderr)
        return 1

    parts = [
        "#pragma once",
        "",
        "// Generated by wclap/tools/embed_presets.py - do not edit.",
        "",
        "namespace spiral303",
        "{",
        "    namespace FactoryPresetData",
        "    {",
        "        struct Entry",
        "        {",
        "            const char* name;",
        "            const char* text;",
        "            int size;",
        "        };",
        "",
        "        inline constexpr Entry entries[] =",
        "        {",
    ]

    count = 0
    for path in files:
        text = path.read_text(encoding="utf-8")
        # A broken preset must not break the build: keep it, but note it.
        try:
            json.loads(text)
        except json.JSONDecodeError as exc:
            print(f"warning: {path.name} is not valid JSON: {exc}", file=sys.stderr)

        parts.append(f"            // {path.name}")
        parts.append("            {")
        parts.append(f'                "{path.name}",')
        parts.append(c_string(text))
        parts.append(f"                {len(text.encode('utf-8'))},")
        parts.append("            },")
        count += 1

    parts.append("        };")
    parts.append("")
    parts.append(f"        inline constexpr int entryCount = {count};")
    parts.append("    }")
    parts.append("}")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"embedded {count} presets into {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
